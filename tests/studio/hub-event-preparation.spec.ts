import {test,expect} from '@playwright/test';
test.use({serviceWorkers:'block'});
test('mobile original Hub calendar event → preparation task and note; owner records unchanged until review',async({page})=>{
 test.setTimeout(90_000);
 await page.setViewportSize({width:390,height:844});
 await page.goto('/home/tasks/?filter=all');
 await expect(page.locator('[data-workspace-status]')).toContainText('saved locally');
 await page.locator('[data-action=new-task]').first().click();
 await page.getByLabel('Task',{exact:true}).fill('Differential Equations exercise sheet');
 await page.getByLabel('Due date',{exact:true}).fill('');
 await page.locator('[data-dialog-submit]').click();
 await expect(page.locator('[data-workspace-dialog]')).not.toBeVisible();
 await page.goto('/home/calendar/?date=2027-02-10');
 await page.locator('[data-action=new-event]').first().click();
 await page.getByLabel('Event',{exact:true}).fill('Differential Equations seminar');
 await page.getByLabel('Start date',{exact:true}).fill('2027-02-10');
 await page.getByLabel('End date',{exact:true}).fill('2027-02-10');
 await page.getByLabel('Start time',{exact:true}).fill('09:00');
 await page.getByLabel('End time',{exact:true}).fill('10:00');
 await page.locator('[data-dialog-submit]').click();
 await expect(page.locator('[data-workspace-dialog]')).not.toBeVisible();
 const event=page.locator('[data-planning-review] .ws-plan-record').filter({hasText:'Differential Equations seminar'});
 await expect(event).toHaveCount(1);
 await event.locator('[data-action=context-event]').click();
 const prep=page.locator('[data-event-preparation]');
 await expect(prep).toBeVisible();
 await expect(prep).toContainText('Differential Equations exercise sheet');
 await expect(prep).toContainText('Existing related Hub work');
 await prep.locator('[data-action=prep-event-task]').click();
 await expect(page.getByLabel('Task',{exact:true})).toHaveValue('Prepare for Differential Equations seminar');
 await expect(page.getByLabel('Due date',{exact:true})).toHaveValue('2027-02-09');
 await page.locator('[data-workspace-dialog] [data-action=close-dialog]').first().click();
 // Cancelling leaves original Hub task and calendar event intact.
 await expect(event).toHaveCount(1);
 await event.locator('[data-action=context-event]').click();
 await page.locator('[data-event-preparation] [data-action=prep-event-note]').click();
 await expect(page.getByLabel('Title',{exact:true})).toHaveValue('Event notes · Differential Equations seminar');
 await expect(page.getByLabel('Note',{exact:true})).toContainText('Follow-up actions');
 await page.locator('[data-workspace-dialog] [data-action=close-dialog]').first().click();
 await event.locator('[data-action=context-event]').click();
 await page.locator('[data-event-preparation] [data-action=followup-event-task]').click();
 await expect(page.getByLabel('Task',{exact:true})).toHaveValue('Follow up: Differential Equations seminar');
 await expect(page.getByLabel('Due date',{exact:true})).toHaveValue('2027-02-11');
 await page.locator('[data-dialog-submit]').click();
 await expect(page.locator('[data-workspace-dialog]')).not.toBeVisible();
 await page.goto('/home/tasks/?filter=all');
 await expect(page.locator('.ws-task-results')).toContainText('Follow up: Differential Equations seminar');
 const count=await page.locator('.ws-task-results .ws-task-entry')
   .filter({hasText:'Follow up: Differential Equations seminar'}).count();
 expect(count).toBe(1);
 const width=await page.evaluate(()=>document.documentElement.scrollWidth);
 expect(width).toBeLessThanOrEqual(390);
});
