import {test,expect} from '@playwright/test';
test.use({serviceWorkers:'block'});
test('mobile guided Weekly Review moves across original task, time, tracker, decision and reflection',async({page})=>{
 test.setTimeout(90_000);
 await page.setViewportSize({width:390,height:844});
 await page.goto('/home/tasks/?filter=all');
 await expect(page.locator('[data-workspace-status]')).toContainText('saved locally');
 await page.locator('[data-action=new-task]').first().click();
 await page.getByLabel('Task',{exact:true}).fill('Weekly review original assignment');
 await page.getByLabel('Due date',{exact:true}).fill('');
 await page.locator('[data-dialog-submit]').click();
 await expect(page.locator('[data-workspace-dialog]')).not.toBeVisible();
 await page.goto('/?mode=review');
 const review=page.locator('[data-weekly-review]');
 await expect(review).toHaveAttribute('data-review-stage','triage');
 await expect(review.locator('.ws-review-stages [data-action=weekly-review-stage]')).toHaveCount(5);
 await expect(review).toContainText('Weekly review original assignment');
 await review.locator('[data-action=unified-triage]').first().click();
 await expect(page.locator('[data-unified-review]')).toBeVisible();
 await page.locator('[data-workspace-dialog] [data-action=close-dialog]').first().click();
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=calendar]').click();
 await expect(review).toHaveAttribute('data-review-stage','calendar');
 await expect(review).toContainText('Original owner calendars and reminders');
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=routines]').click();
 await expect(review).toHaveAttribute('data-review-stage','routines');
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=decisions]').click();
 await expect(review).toHaveAttribute('data-review-stage','decisions');
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=finish]').click();
 await expect(review).toHaveAttribute('data-review-stage','finish');
 await page.locator('[data-weekly-review-field=reflection]').fill('Worked through the material.');
 await page.locator('[data-weekly-review-field=priority]').fill('Complete remaining proof questions.');
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=triage]').click();
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=finish]').click();
 await expect(page.locator('[data-weekly-review-field=priority]'))
   .toHaveValue('Complete remaining proof questions.');
 await review.locator('[data-action=weekly-review-note]').click();
 await expect(page.getByLabel('Title',{exact:true})).toHaveValue(/Weekly review/);
 await expect(page.getByLabel('Note',{exact:true})).toHaveValue(/Complete remaining proof questions/);
 // Cancel does not create any review completion record or note.
 await page.locator('[data-workspace-dialog] [data-action=close-dialog]').first().click();
 await expect(review).toHaveAttribute('data-review-stage','finish');
 await review.locator('[data-action=weekly-review-note]').click();
 await page.locator('[data-dialog-submit]').click();
 await expect(page.locator('[data-workspace-dialog]')).not.toBeVisible();
 await expect(page.locator('[data-workspace-status]')).toContainText('saved locally');
 await review.locator('[data-action=unified-mode][data-id=today]').click();
 await page.locator('[data-action=toggle-today-more]').click();
 await expect(page.locator('[data-today-workbench]')).toContainText('Weekly review');
 await page.goto('/?mode=review');
 await expect(page.locator('[data-weekly-review]')).toHaveAttribute('data-review-stage','triage');
 await expect(page.locator('[data-weekly-review-field]')).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});
test('desktop review uses original calendar, decisions and outcome destinations without a new store',async({page})=>{
 await page.setViewportSize({width:1440,height:900});
 await page.goto('/?mode=review');
 const review=page.locator('[data-weekly-review]');
 await expect(review).toBeVisible();
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=calendar]').click();
 await expect(review.locator('.ws-review-days li')).toHaveCount(7);
 await expect(review).toContainText('Open Folio planner');
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=routines]').click();
 await expect(review).toContainText('Tracker check-ins');
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=decisions]').click();
 await expect(review).toContainText('Decision review');
 await review.locator('.ws-review-stages [data-action=weekly-review-stage][data-id=finish]').click();
 await expect(review).toContainText('not a completed-review audit');
 const full=await page.evaluate(()=>document.documentElement.scrollWidth);
 expect(full).toBeLessThanOrEqual(1440);
});
