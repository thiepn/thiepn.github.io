 await page.locator('[data-office-search]').fill('absent word');
 await expect(page.locator('[data-office-count]')).toContainText('0 of 2');
 await page.locator('[data-office-search]').fill('');
 await page.locator('[data-office-sort]').selectOption('title');
 await expect(page.locator('[data-office-list] .office-entry')).toHaveCount(2);
 await expect(page.locator('[data-office-list] .office-entry').first()).toContainText('DGL worksheet');
 await page.locator('[data-office-list] .office-entry').filter({hasText:'Stochastik'}).click();
 await expect(page.locator('[data-office-outline] [data-office-heading]')).toHaveCount(2);
 await page.locator('[data-office-mode=preview]').click();
 await page.locator('[data-office-outline] button').filter({hasText:'Conditional probability'}).click();
 await expect(page.locator('.office-source')).toBeVisible();
 expect(await page.locator('[data-office-body]').evaluate((node:HTMLTextAreaElement)=>node.selectionStart)).toBe(27);
 const download=page.waitForEvent('download');
