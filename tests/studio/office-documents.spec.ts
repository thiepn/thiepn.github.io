import {test,expect} from '@playwright/test';
test('Office native Markdown autosave, reload, history restore and export',async({page})=>{
 await page.goto('/home/documents/');
 await expect(page.locator('[data-office-new]')).toBeEnabled();
 await page.locator('[data-office-new]').click();
 await page.locator('[data-office-title]').fill('Research plan');
 await page.locator('[data-office-body]').fill('# First draft');
 await page.locator('[data-office-save]').click();
 await expect(page.locator('[data-office-status]')).toContainText('Saved locally');
 await page.locator('[data-office-body]').fill('# Revised draft');
 await page.locator('[data-office-save]').click();
 await expect(page.locator('[data-office-status]')).toContainText('Saved locally');
 await page.reload();
 await expect(page.locator('[data-office-body]')).toHaveValue('# Revised draft');
 await page.locator('[data-office-history]').selectOption('1');
 page.once('dialog',dialog=>void dialog.accept());
 await page.locator('[data-office-restore]').click();
 await expect(page.locator('[data-office-body]')).toHaveValue('# First draft');
 await expect(page.locator('[data-office-status]')).toContainText('Saved locally');
 const downloaded=page.waitForEvent('download');
 await page.locator('[data-office-export]').click();
 expect((await downloaded).suggestedFilename()).toBe('Research plan.md');
});
test('Office concurrent edits fail closed and retain local export',async({page,context})=>{
 await page.goto('/home/documents/');
 await expect(page.locator('[data-office-new]')).toBeEnabled();
 await page.locator('[data-office-new]').click();
 await page.locator('[data-office-body]').fill('Initial');
 await page.locator('[data-office-save]').click();
 await expect(page.locator('[data-office-status]')).toContainText('Saved locally');
 const other=await context.newPage();
 await other.goto('/home/documents/');
 await expect(other.locator('[data-office-body]')).toHaveValue('Initial');
 await page.locator('[data-office-body]').fill('First editor');
 await page.locator('[data-office-save]').click();
 await expect(page.locator('[data-office-status]')).toContainText('Saved locally');
 await other.locator('[data-office-body]').fill('Second editor');
 await other.locator('[data-office-save]').click();
 await expect(other.locator('[data-office-status]')).toContainText('changed in another tab');
 await expect(other.locator('[data-office-export]')).toBeEnabled();
 await page.reload();
 await expect(page.locator('[data-office-body]')).toHaveValue('First editor');
 await other.close();
});
test('Office stays in Hub shell on narrow viewport and hides during Hub privacy mask',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/home/documents/');
 await expect(page.locator('[data-office-new]')).toBeEnabled();
 await page.locator('[data-office-new]').click();
 await page.locator('[data-office-body]').fill('Private work');
 await page.locator('[data-office-save]').click();
 await expect(page.locator('[data-office-status]')).toContainText('Saved locally');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.locator('[data-workspace] [data-action=account]').first().click();
 await page.locator('[data-account-dialog] [data-action=privacy]').click();
 await expect(page.locator('[data-workspace]')).toHaveAttribute('data-calendar-private','true');
 await expect(page.locator('[data-office-body]')).toBeDisabled();
 await expect(page.locator('[data-office-body]')).toHaveValue('');
});
