test('O4 standalone HTML export contains escaped markup and same safe preview',async({page})=>{
 await page.goto('/home/documents/');
 await expect(page.locator('[data-office-new]')).toBeEnabled();
 await page.locator('[data-office-new]').click();
 await page.locator('[data-office-title]').fill('Safe <script> title');
 await page.locator('[data-office-body]').fill('# Heading\n\n<script>window.pwned=1</script>\n\n**Strong** [Link](https://example.com)');
 const pending=page.waitForEvent('download');
 await page.locator('[data-office-html]').click();
 const dl=await pending;
 expect(dl.suggestedFilename()).toBe('Safe -script- title.html');
 const markup=await (await import('node:fs/promises')).readFile((await dl.path())!,'utf8');
 expect(markup).toContain("default-src 'none'");
 expect(markup).toContain('&lt;script&gt;window.pwned=1&lt;/script&gt;');
 expect(markup).not.toMatch(/<script\b/i);
 expect(markup).toContain('<strong>Strong</strong>');
 expect(markup).toContain('rel="noopener noreferrer"');
 expect(await page.evaluate(()=>(window as any).pwned)).toBeUndefined();
});
